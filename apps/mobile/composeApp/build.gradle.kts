// Integration tests talk to the mock API; pass its URL through and always re-run them.
tasks.named<Test>("jvmTest") {
    System.getenv("SUBSCRIBBY_API_URL")?.let { systemProperty("subscribby.apiUrl", it) }
    outputs.upToDateWhen { false }
    testLogging {
        events("passed", "skipped", "failed")
        showStandardStreams = true
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}

// With AGP 9 the APK is built by :androidApp. Keep the familiar command working:
// `./gradlew :composeApp:assembleDebug` == `./gradlew :androidApp:assembleDebug`.
tasks.register("assembleDebug") {
    group = "build"
    description = "Builds the Android debug APK (alias for :androidApp:assembleDebug)."
    dependsOn(":androidApp:assembleDebug")
}
